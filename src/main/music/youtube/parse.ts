import type { YouTubeCandidate } from './types'

const VIDEO_ID_PATTERN = /^[A-Za-z0-9_-]{11}$/
const MAX_DURATION_MS = 86_400_000
const ESCAPE_CHARACTER = String.fromCharCode(27)
const ANSI_PATTERN = new RegExp(`${ESCAPE_CHARACTER}\\[[0-?]*[ -/]*[@-~]`, 'g')
const API_KEY_PATTERN = /AIza[0-9A-Za-z_-]{10,}/g
const API_KEY_PARAM_PATTERN = /([?&]key(?:=|%3D))[^&\s]+/gi
const TITLE_SEPARATOR_PATTERN = /\s+[-\u2013\u2014]\s+/
const PAREN_TAG_PATTERN = /\(([^)]*)\)/g
const SQUARE_TAG_PATTERN = /\[([^\]]*)\]/g
const VARIANT_WORD_PATTERN =
  /\b(official|lyrics?|audio|video|visuali[sz]er|hd|hdr|4k|8k|explicit|clean|remaster(?:ed)?|m\/?v|mv)\b/i
const SUFFIX_VARIANT_PATTERN =
  /\s*[|\u2013\u2014-]\s*(?:official\s+)?(?:music\s+)?(?:video|audio|lyric\s+video|lyrics?|visuali[sz]er|m\/?v|mv|hd|hdr|4k|8k|explicit|clean|remaster(?:ed)?)\s*$/i
const GENERIC_CHANNELS = new Set([
  'youtube',
  'youtube music',
  'music',
  'topic',
  'various artists',
  'auto-generated by youtube',
])

const HTML_ENTITIES: Record<string, string> = {
  amp: '&',
  apos: "'",
  gt: '>',
  hellip: '\u2026',
  lt: '<',
  mdash: '\u2014',
  nbsp: ' ',
  ndash: '\u2013',
  quot: '"',
}

export function isYouTubeVideoId(value: unknown): value is string {
  return typeof value === 'string' && VIDEO_ID_PATTERN.test(value)
}

export function youtubeWatchUrl(videoId: string): string {
  return `https://www.youtube.com/watch?v=${videoId}`
}

export function youtubeThumbnailUrl(
  videoId: string,
  quality: 'hqdefault' | 'maxresdefault' = 'hqdefault',
): string {
  return `https://i.ytimg.com/vi/${videoId}/${quality}.jpg`
}

const THUMBNAIL_HOSTS = new Set(['i.ytimg.com', 'img.youtube.com', 'i9.ytimg.com'])

/**
 * The Data API returns thumbnail URLs inside untrusted JSON. Only the fixed
 * YouTube image hosts may reach the protocol proxy, so a compromised or
 * malformed response cannot turn artwork into an SSRF probe.
 */
export function youtubeThumbnailUrlFromApi(value: unknown): string | null {
  if (typeof value !== 'string' || value.length > 2_048) return null
  try {
    const url = new URL(value)
    if (url.protocol !== 'https:') return null
    if (!THUMBNAIL_HOSTS.has(url.hostname.toLowerCase())) return null
    return url.toString()
  } catch {
    return null
  }
}

/** Converts the ISO-8601 durations used by the YouTube Data API into milliseconds. */
export function parseIsoDuration(value: string): number {
  const match =
    /^P(?:(\d+)D)?(?:T(?:(\d+)H)?(?:(\d+)M)?(?:(\d+(?:\.\d+)?)S)?)?$/.exec(value.trim())
  if (!match) return 0
  const days = Number(match[1] ?? 0)
  const hours = Number(match[2] ?? 0)
  const minutes = Number(match[3] ?? 0)
  const seconds = Number(match[4] ?? 0)
  const total =
    days * 86_400_000 + hours * 3_600_000 + minutes * 60_000 + seconds * 1_000
  if (!Number.isFinite(total) || total <= 0) return 0
  return Math.min(Math.round(total), MAX_DURATION_MS)
}

export function decodeHtmlEntities(value: string): string {
  return value.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (match, entity: string) => {
    if (entity.toLowerCase().startsWith('#x')) {
      const code = Number.parseInt(entity.slice(2), 16)
      return Number.isFinite(code) && code > 0 && code <= 0x10ffff
        ? String.fromCodePoint(code)
        : match
    }
    if (entity.startsWith('#')) {
      const code = Number.parseInt(entity.slice(1), 10)
      return Number.isFinite(code) && code > 0 && code <= 0x10ffff
        ? String.fromCodePoint(code)
        : match
    }
    return HTML_ENTITIES[entity.toLowerCase()] ?? match
  })
}

function cleanTitle(value: string): string {
  const stripVariant = (match: string, inner: string): string =>
    VARIANT_WORD_PATTERN.test(inner) ? ' ' : match
  let title = value
    .replace(PAREN_TAG_PATTERN, stripVariant)
    .replace(SQUARE_TAG_PATTERN, stripVariant)
  for (let index = 0; index < 3; index += 1) {
    const next = title.replace(SUFFIX_VARIANT_PATTERN, '')
    if (next === title) break
    title = next
  }
  return title
    .replace(/\s+/g, ' ')
    .replace(/^[\s\-–—|:]+|[\s\-–—|:]+$/g, '')
    .trim()
}

function normalizeName(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '')
}

export function cleanChannelName(value: string): string {
  const channel = decodeHtmlEntities(value)
    .replace(/\s+-\s+topic$/i, '')
    .replace(/\s+/g, ' ')
    .trim()
  if (!channel || GENERIC_CHANNELS.has(channel.toLowerCase())) return ''
  return channel
}

const LEADING_TAG_PATTERN = /^(?:\[[^\]]*\]|\([^)]*\))\s*/

/**
 * Music-show uploads often prefix the artist with a bracket tag, as in
 * `[HOT DEBUT] A2O LITE - NEON`. The tag is not part of the artist name.
 */
function stripLeadingTags(value: string): string {
  let result = value.trim()
  for (let index = 0; index < 3; index += 1) {
    const next = result.replace(LEADING_TAG_PATTERN, '').trim()
    if (next === result) break
    result = next
  }
  return result
}

export interface ParsedYouTubeTitle {
  title: string
  artist: string
}

/**
 * YouTube has no separate artist field. Most music uploads use
 * `Artist - Song`, and official channels either match that prefix or provide
 * the artist through a `- Topic` channel name. The rest fall back to the
 * channel so a row never renders an empty artist.
 */
export function parseYouTubeTitle(rawTitle: string, rawChannel: string): ParsedYouTubeTitle {
  const decodedTitle = decodeHtmlEntities(rawTitle).replace(/\s+/g, ' ').trim()
  const channel = cleanChannelName(rawChannel)
  const cleaned = cleanTitle(decodedTitle) || decodedTitle || 'YouTube video'
  const parts = TITLE_SEPARATOR_PATTERN.exec(cleaned)
  if (parts && parts.index > 0) {
    const left = stripLeadingTags(cleaned.slice(0, parts.index))
    const right = cleaned.slice(parts.index + parts[0].length).trim()
    if (left && right) {
      const artist =
        channel && normalizeName(left) === normalizeName(channel) ? channel : left
      return { title: right, artist: artist || 'YouTube' }
    }
  }
  return { title: cleaned, artist: channel || 'YouTube' }
}

function durationMs(value: unknown): number {
  const seconds = typeof value === 'number' ? value : Number(value)
  if (!Number.isFinite(seconds) || seconds <= 0) return 0
  return Math.min(Math.round(seconds * 1_000), MAX_DURATION_MS)
}

function text(value: unknown): string {
  return typeof value === 'string' ? value.trim() : ''
}

/** Parses the JSON-lines output of `yt-dlp --flat-playlist --dump-json`. */
export function parseYtDlpSearch(stdout: string): YouTubeCandidate[] {
  const candidates: YouTubeCandidate[] = []
  const seen = new Set<string>()

  for (const line of stdout.split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed.startsWith('{')) continue
    let raw: Record<string, unknown>
    try {
      raw = JSON.parse(trimmed) as Record<string, unknown>
    } catch {
      continue
    }

    const videoId = text(raw['id']) || text(raw['video_id'])
    if (!isYouTubeVideoId(videoId) || seen.has(videoId)) continue
    const liveStatus = text(raw['live_status'])
    if (liveStatus === 'is_live' || liveStatus === 'is_upcoming') continue
    const title = text(raw['title'])
    const length = durationMs(raw['duration'])
    if (!title || length === 0) continue

    const channel = cleanChannelName(text(raw['channel']) || text(raw['uploader']))
    const parsed = parseYouTubeTitle(title, channel)
    seen.add(videoId)
    candidates.push({
      videoId,
      title: parsed.title,
      videoTitle: title,
      artist: parsed.artist,
      channel: channel || parsed.artist,
      durationMs: length,
      thumbnailUrl: youtubeThumbnailUrl(videoId),
      sourceUrl: youtubeWatchUrl(videoId),
    })
  }

  return candidates
}

export function redactSecrets(value: string): string {
  return value
    .replace(API_KEY_PATTERN, '[redacted]')
    .replace(API_KEY_PARAM_PATTERN, '$1[redacted]')
}

/**
 * Command failures and API responses are untrusted text. Strip credentials,
 * terminal escape codes, and control characters before they reach the renderer.
 */
function stripControlCharacters(value: string): string {
  let output = ''
  for (const character of value) {
    const code = character.codePointAt(0) ?? 0
    output += code < 0x20 || code === 0x7f ? ' ' : character
  }
  return output
}

export function safeErrorMessage(error: unknown, fallback: string): string {
  if (error instanceof Error && error.name === 'AbortError') return fallback
  const raw =
    error instanceof Error
      ? error.message
      : typeof error === 'string'
        ? error
        : ''
  const cleaned = redactSecrets(stripControlCharacters(raw.replace(ANSI_PATTERN, '')))
    .replace(/\s+/g, ' ')
    .trim()
  return (cleaned || fallback).slice(0, 240)
}
