import { describe, expect, it } from 'vitest'
import {
  cleanChannelName,
  decodeHtmlEntities,
  isYouTubeVideoId,
  parseIsoDuration,
  parseYouTubeTitle,
  parseYtDlpSearch,
  redactSecrets,
  safeErrorMessage,
  youtubeThumbnailUrl,
  youtubeThumbnailUrlFromApi,
  youtubeWatchUrl,
} from './parse'

describe('YouTube video ids', () => {
  it('accepts 11-character ids from both URL alphabets', () => {
    expect(isYouTubeVideoId('dQw4w9WgXcQ')).toBe(true)
    expect(isYouTubeVideoId('9bZkp7q19f0')).toBe(true)
    expect(isYouTubeVideoId('a_b-c_D-EFg')).toBe(true)
  })

  it('rejects ids with the wrong length or characters', () => {
    expect(isYouTubeVideoId('short')).toBe(false)
    expect(isYouTubeVideoId('dQw4w9WgXcQ!')).toBe(false)
    expect(isYouTubeVideoId('https://youtube.com/watch?v=dQw4w9WgXcQ')).toBe(false)
    expect(isYouTubeVideoId(null)).toBe(false)
  })

  it('builds canonical watch and thumbnail URLs', () => {
    expect(youtubeWatchUrl('dQw4w9WgXcQ')).toBe(
      'https://www.youtube.com/watch?v=dQw4w9WgXcQ',
    )
    expect(youtubeThumbnailUrl('dQw4w9WgXcQ')).toBe(
      'https://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg',
    )
    expect(youtubeThumbnailUrl('dQw4w9WgXcQ', 'maxresdefault')).toBe(
      'https://i.ytimg.com/vi/dQw4w9WgXcQ/maxresdefault.jpg',
    )
  })
})

describe('youtubeThumbnailUrlFromApi', () => {
  it('accepts HTTPS images on the YouTube image hosts', () => {
    expect(
      youtubeThumbnailUrlFromApi('https://i.ytimg.com/vi/dQw4w9WgXcQ/maxresdefault.jpg'),
    ).toBe('https://i.ytimg.com/vi/dQw4w9WgXcQ/maxresdefault.jpg')
    expect(
      youtubeThumbnailUrlFromApi('https://img.youtube.com/vi/dQw4w9WgXcQ/hqdefault.jpg'),
    ).toBe('https://img.youtube.com/vi/dQw4w9WgXcQ/hqdefault.jpg')
    expect(
      youtubeThumbnailUrlFromApi('https://i9.ytimg.com/vi/dQw4w9WgXcQ/maxresdefault.jpg'),
    ).toBe('https://i9.ytimg.com/vi/dQw4w9WgXcQ/maxresdefault.jpg')
  })

  it('rejects other hosts, plain HTTP, and non-strings', () => {
    expect(youtubeThumbnailUrlFromApi('https://example.com/cover.jpg')).toBeNull()
    expect(
      youtubeThumbnailUrlFromApi('https://i.ytimg.com.evil.test/vi/x/hqdefault.jpg'),
    ).toBeNull()
    expect(
      youtubeThumbnailUrlFromApi('http://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg'),
    ).toBeNull()
    expect(youtubeThumbnailUrlFromApi('not a url')).toBeNull()
    expect(youtubeThumbnailUrlFromApi(null)).toBeNull()
    expect(youtubeThumbnailUrlFromApi(42)).toBeNull()
  })
})

describe('cleanChannelName', () => {
  it('strips a Topic suffix and decodes entities', () => {
    expect(cleanChannelName('The Weeknd - Topic')).toBe('The Weeknd')
    expect(cleanChannelName('Simon &amp; Garfunkel - Topic')).toBe('Simon & Garfunkel')
    expect(cleanChannelName('  Rick   Astley  ')).toBe('Rick Astley')
  })

  it('drops generic platform channel names', () => {
    expect(cleanChannelName('YouTube')).toBe('')
    expect(cleanChannelName('YouTube Music')).toBe('')
    expect(cleanChannelName('Auto-generated by YouTube')).toBe('')
    expect(cleanChannelName('Various Artists')).toBe('')
  })
})

describe('parseIsoDuration', () => {
  it('parses hours, minutes, seconds, and fractions', () => {
    expect(parseIsoDuration('PT3M33S')).toBe(213_000)
    expect(parseIsoDuration('PT1H2M3.5S')).toBe(3_723_500)
    expect(parseIsoDuration('PT45S')).toBe(45_000)
  })

  it('treats live placeholders and malformed values as zero', () => {
    expect(parseIsoDuration('P0D')).toBe(0)
    expect(parseIsoDuration('')).toBe(0)
    expect(parseIsoDuration('3:33')).toBe(0)
  })
})

describe('decodeHtmlEntities', () => {
  it('decodes named and numeric entities', () => {
    expect(decodeHtmlEntities('Rock &amp; Roll')).toBe('Rock & Roll')
    expect(decodeHtmlEntities('Livin&#39; On A Prayer')).toBe("Livin' On A Prayer")
    expect(decodeHtmlEntities('&#x27;90s')).toBe("'90s")
    expect(decodeHtmlEntities('&unknown;')).toBe('&unknown;')
  })
})

describe('parseYouTubeTitle', () => {
  it('splits the common artist prefix and strips official tags', () => {
    expect(
      parseYouTubeTitle(
        'The Weeknd - Blinding Lights (Official Video)',
        'The Weeknd',
      ),
    ).toEqual({ title: 'Blinding Lights', artist: 'The Weeknd' })
    expect(
      parseYouTubeTitle(
        'Daft Punk - One More Time (Official Audio) [4K]',
        'Daft Punk',
      ),
    ).toEqual({ title: 'One More Time', artist: 'Daft Punk' })
  })

  it('strips a suffix such as | Official Music Video', () => {
    expect(
      parseYouTubeTitle('Artist - Song | Official Music Video', 'Artist'),
    ).toEqual({ title: 'Song', artist: 'Artist' })
  })

  it('uses a Topic channel as the artist when the title has no prefix', () => {
    expect(parseYouTubeTitle('Blinding Lights', 'The Weeknd - Topic')).toEqual({
      title: 'Blinding Lights',
      artist: 'The Weeknd',
    })
  })

  it('falls back to the channel for ordinary uploads', () => {
    expect(parseYouTubeTitle('A Rare Live Session', 'Tiny Desk')).toEqual({
      title: 'A Rare Live Session',
      artist: 'Tiny Desk',
    })
  })

  it('keeps a hyphen inside an artist name', () => {
    expect(parseYouTubeTitle('Jay-Z - 99 Problems', 'Jay-Z')).toEqual({
      title: '99 Problems',
      artist: 'Jay-Z',
    })
  })

  it('decodes entities before splitting', () => {
    expect(
      parseYouTubeTitle('Bon Jovi - Livin&#39; On A Prayer', 'Bon Jovi'),
    ).toEqual({ title: "Livin' On A Prayer", artist: 'Bon Jovi' })
  })

  it('does not use a generic channel as the artist', () => {
    expect(parseYouTubeTitle('Some Song (Official Video)', 'YouTube Music')).toEqual({
      title: 'Some Song',
      artist: 'YouTube',
    })
  })

  it('drops a leading bracket tag before the artist', () => {
    expect(
      parseYouTubeTitle(
        '[HOT DEBUT] A2O LITE - NEON l Show Champion l EP.615 l 261021',
        'ALL THE K-POP',
      ),
    ).toEqual({
      title: 'NEON l Show Champion l EP.615 l 261021',
      artist: 'A2O LITE',
    })
    expect(
      parseYouTubeTitle('[THE SHOW CHOICE] NEON', 'THE K-POP'),
    ).toEqual({ title: '[THE SHOW CHOICE] NEON', artist: 'THE K-POP' })
  })
})

describe('parseYtDlpSearch', () => {
  it('reads JSON lines, skips live and malformed rows, and deduplicates', () => {
    const stdout = [
      JSON.stringify({
        id: 'dQw4w9WgXcQ',
        title: 'Rick Astley - Never Gonna Give You Up (Official Video)',
        duration: 213,
        channel: 'Rick Astley',
        live_status: 'not_live',
      }),
      'not json at all',
      JSON.stringify({ id: 'too-short', title: 'Ignored', duration: 10 }),
      JSON.stringify({
        id: '9bZkp7q19f0',
        title: 'PSY - GANGNAM STYLE (Official Video)',
        duration: 252,
        uploader: 'officialpsy',
        live_status: 'not_live',
      }),
      JSON.stringify({
        id: 'dQw4w9WgXcQ',
        title: 'Duplicate',
        duration: 1,
        channel: 'Rick Astley',
      }),
      JSON.stringify({
        id: 'live1234567',
        title: 'Live stream',
        duration: 0,
        channel: 'Streamer',
        live_status: 'is_live',
      }),
    ].join('\n')

    const candidates = parseYtDlpSearch(stdout)
    expect(candidates).toHaveLength(2)
    expect(candidates[0]).toMatchObject({
      videoId: 'dQw4w9WgXcQ',
      title: 'Never Gonna Give You Up',
      artist: 'Rick Astley',
      channel: 'Rick Astley',
      durationMs: 213_000,
      sourceUrl: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ',
    })
    expect(candidates[1]).toMatchObject({
      videoId: '9bZkp7q19f0',
      title: 'GANGNAM STYLE',
      artist: 'PSY',
      channel: 'officialpsy',
      durationMs: 252_000,
    })
  })
})

describe('error redaction', () => {
  it('removes API keys from URLs and messages', () => {
    const key = ['AIza', 'SyTestKeyValue1234567890'].join('')
    const message = safeErrorMessage(
      new Error(`request failed: https://www.googleapis.com/youtube/v3/search?key=${key}`),
      'fallback',
    )
    expect(message).not.toContain(key)
    expect(message).not.toContain('AIza')
    expect(message).toContain('key=[redacted]')
  })

  it('replaces key parameters without an API-key prefix', () => {
    expect(redactSecrets('https://example.test?key=abc123&x=1')).toBe(
      'https://example.test?key=[redacted]&x=1',
    )
  })

  it('strips terminal escape codes and control characters', () => {
    const message = safeErrorMessage('\u001b[31mERROR\u001b[0m\u0000 failed', 'fallback')
    expect(message).toBe('ERROR failed')
  })
})
